"""Write a compact summary of the shared code's public names, for use as chat context.

Run from the repo root (with the package installed) and save the output:

    python scripts/make_api_summary.py > docs/api-summary.md

For every module it lists the public functions (with their signatures), the data containers
(with their fields), the exceptions and the constants, each with the first line of its
docstring. It reads the code itself, so it cannot drift from it. Re-run it whenever a public
name changes. It never imports OR-Tools (solver.py loads that only when a search runs).
"""

from __future__ import annotations

import dataclasses
import enum
import importlib
import inspect
import re

# Layer order: a module only depends on the ones before it (see docs/repo-structure.md).
MODULES = ("models", "io", "conflicts", "selection", "report", "validator", "solver", "cli")


def first_line(obj: object) -> str:
    """The first sentence of the docstring, on one line."""
    paragraph = (inspect.getdoc(obj) or "").strip().split("\n\n")[0]
    text = " ".join(paragraph.split())
    return re.split(r"(?<=[.!?])\s", text)[0] if text else ""


def signature(function: object) -> str:
    return str(inspect.signature(function)).replace("'", "")


def describe_class(cls: type) -> list[str]:
    summary = first_line(cls)
    if issubclass(cls, enum.Enum):
        members = ", ".join(member.name for member in cls)
        return [f"- `{cls.__name__}` (choices: {members}) - {summary}"]
    if issubclass(cls, BaseException):
        return [f"- `{cls.__name__}` (exception) - {summary}"]
    if dataclasses.is_dataclass(cls):
        fields = ", ".join(f"{f.name}: {str(f.type).replace(chr(39), '')}" for f in dataclasses.fields(cls))
        line = f"- `{cls.__name__}({fields})` - {summary}"
        extras = [
            name + ("" if isinstance(member, property) else "()")
            for name, member in vars(cls).items()
            if not name.startswith("_")
            and (isinstance(member, property) or inspect.isfunction(member))
        ]
        if extras:
            line += f" Also: {', '.join(extras)}."
        return [line]
    return [f"- `{cls.__name__}` - {summary}"]


_listed_constants: set[str] = set()


def describe_module(name: str) -> list[str]:
    module = importlib.import_module(f"performance_scheduling.{name}")
    lines = [f"## {name}.py", "", first_line(module), ""]
    body: list[str] = []
    for member_name, member in vars(module).items():
        if member_name.startswith("_") or getattr(member, "__module__", None) != module.__name__:
            if (
                member_name.isupper()
                and not member_name.startswith("_")
                and isinstance(member, (int, float, str))
                and member_name not in _listed_constants  # re-exported from an earlier module
            ):
                _listed_constants.add(member_name)
                body.append(f"- `{member_name} = {member!r}`")
            continue
        if inspect.isclass(member):
            body.extend(describe_class(member))
        elif inspect.isfunction(member):
            body.append(f"- `{member_name}{signature(member)}` - {first_line(member)}")
    return lines + body + [""]


def main() -> None:
    print("# API summary")
    print()
    print(
        "Generated by `scripts/make_api_summary.py` from the code. Do not edit by hand; "
        "re-run the script when a public name changes. Modules are listed in layer order: "
        "a module only uses the ones above it. Names starting with `_` are private and left out."
    )
    print()
    for name in MODULES:
        print("\n".join(describe_module(name)))


if __name__ == "__main__":
    main()
